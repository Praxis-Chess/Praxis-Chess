import * as fs from 'fs'
import * as path from 'path'
import { test } from '../fixtures/test'
import { collect, expandAll, metrics, pairs, type Golden } from '../fixtures/readability'
import { STATES, open, vocabulary } from '../fixtures/parity/states'

/**
 * Not a test: writes the parity goldens, the record of what every screen shows
 * BEFORE the readability work changes it (docs/design/READABILITY_PLAN.md).
 *
 * Run it only to re-baseline, and review the diff of SUMMARY.md when you do:
 *   PARITY_CAPTURE=1 npx playwright test parity-capture --project=chromium
 * Only some states (never overwrite the goldens of finished work):
 *   PARITY_CAPTURE=1 PARITY_ONLY=play/one-game npx playwright test parity-capture --project=chromium
 */
const DIR = path.join(__dirname, '../fixtures/parity')
const GOLDEN = path.join(DIR, 'golden')

test.skip(!process.env.PARITY_CAPTURE, 'Writes goldens; set PARITY_CAPTURE=1 to re-baseline')
test.describe.configure({ mode: 'serial' })
test.use({ viewport: { width: 1440, height: 900 }, locale: 'en-US', timezoneId: 'UTC' })

const vocab = vocabulary()

// PARITY_ONLY=play/one-game,play/six-games captures just those states, so adding a
// state never re-baselines the others (their goldens are the before of earlier work).
const only = process.env.PARITY_ONLY?.split(',').filter(Boolean)

for (const s of STATES) {
  test(`${s.screen} · ${s.state}`, async ({ page, api }, info) => {
    test.skip(info.project.name !== 'chromium', 'Goldens come from the desktop rendering')
    test.skip(!!only && !only.includes(`${s.screen}/${s.state}`), 'Not in PARITY_ONLY')
    await open(page, api, s)
    const before = metrics(await collect(page))
    const all = await expandAll(page)
    const golden: Golden = {
      screen: s.screen, state: s.state, path: s.path, metrics: before,
      pairs: pairs(all, vocab),
      methods: all.methods.map(m => [m.scope.join(' > '), m.text] as [string, string]),
    }
    fs.mkdirSync(GOLDEN, { recursive: true })
    fs.writeFileSync(path.join(GOLDEN, `${s.screen}.${s.state}.json`), JSON.stringify(golden, null, 1) + '\n')
  })
}

test.afterAll(() => {
  if (!fs.existsSync(GOLDEN)) return
  const goldens: Golden[] = STATES
    .map(s => path.join(GOLDEN, `${s.screen}.${s.state}.json`))
    .filter(f => fs.existsSync(f))
    .map(f => JSON.parse(fs.readFileSync(f, 'utf8')))
  const ex = JSON.parse(fs.readFileSync(path.join(DIR, 'parity-exceptions.json'), 'utf8'))
  fs.writeFileSync(path.join(DIR, 'SUMMARY.md'), summary(goldens, ex))
})

/** The review artefact: per state, the metrics and the facts per section. Not the raw pairs. */
function summary(goldens: Golden[], ex: Record<string, unknown[]>): string {
  const lines = [
    '# Parity goldens: summary',
    '',
    'Generated by `e2e/tests/parity-capture.spec.ts`. Review this file, not the JSON. Each state lists what the',
    'screen shows by default (prose words, data tokens, paragraphs over 15 words), what it shows only on hover,',
    'and, after every disclosure and popover is opened, how many facts each section holds: numbers and moves,',
    'text data (names, states), and links.',
    'A section is the innermost two named scopes.',
    '',
    '| Screen · state | Prose words | Data tokens | Paragraphs | Facts | Hover-only texts |',
    '|---|---:|---:|---:|---:|---:|',
    ...goldens.map(g => `| ${g.screen} · ${g.state} | ${g.metrics.prose} | ${g.metrics.data} | ${g.metrics.paragraphs.length} | ` +
      `${g.pairs.reduce((a, p) => a + p[2], 0)} | ${g.methods.length} |`),
    '',
    '## Exceptions',
    '',
    ...Object.entries(ex).filter(([k]) => k !== '_doc').map(([k, v]) => `- ${k}: ${(v as unknown[]).length === 0 ? 'none' : (v as unknown[]).length}`),
    '',
  ]
  for (const g of goldens) {
    const bySection = new Map<string, { data: number; text: number; links: number }>()
    for (const [scope, token, n] of g.pairs) {
      const key = scope.split(' > ').slice(-2).join(' › ') || '(page)'
      const e = bySection.get(key) ?? { data: 0, text: 0, links: 0 }
      if (token.startsWith('@')) e.links += n
      else if (token.startsWith('~')) e.text += n
      else e.data += n
      bySection.set(key, e)
    }
    lines.push(`## ${g.screen} · ${g.state}`, '', `\`${g.path}\``, '')
    if (g.metrics.paragraphs.length) {
      lines.push('Paragraphs over 15 words:', '', ...g.metrics.paragraphs.map(p => `- ${p.length > 140 ? p.slice(0, 140) + '…' : p}`), '')
    }
    lines.push('| Section | Numbers, moves | Text data | Links |', '|---|---:|---:|---:|')
    for (const [k, v] of bySection) lines.push(`| ${k.replace(/\|/g, '\\|')} | ${v.data} | ${v.text} | ${v.links} |`)
    if (g.methods.length) {
      const shown = g.methods.slice(0, 8).map(([s, t]) => `- ${s.split(' > ').pop() || '(page)'}: ${t}`)
      if (g.methods.length > 8) shown.push(`- and ${g.methods.length - 8} more`)
      lines.push('', 'Hover-only (`title=`), unreachable by tap or keyboard today:', '', ...shown)
    }
    lines.push('')
  }
  return lines.join('\n')
}
